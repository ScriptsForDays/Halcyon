// Regenerates src/Core/IconData.luau: the Lucide icons that ship inside the
// bundle, so the library's own controls draw without any network request.
//
// Ids come from Footagesus/Icons (MIT), pinned to the commit Icons.luau uses.
// A name that the pack does not contain fails the build.

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const COMMIT = "46d30c19ba7bc601d6ec794a48dc3a89568b1eec";
const URL = `https://raw.githubusercontent.com/Footagesus/Icons/${COMMIT}/lucide/dist/Icons.lua`;
const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "Core", "IconData.luau");

const NAMES = `
x check chevron-down chevron-right chevron-up chevron-left search settings minus plus copy lock lock-open key
key-round crown user users eye eye-off info circle-alert triangle-alert circle-check circle-x bell palette
keyboard house sword swords shield zap star heart target crosshair map map-pin compass rocket flame gem coins
gift trophy gamepad-2 mouse-pointer-2 move maximize-2 minimize-2 panel-left menu ellipsis refresh-cw download
upload save trash-2 folder file file-text code terminal link external-link globe clock calendar sun moon
monitor smartphone cpu wifi activity sliders-horizontal list layout-grid layers box package wrench hammer bug
sparkles bot ghost skull footprints wind droplet leaf mountain car plane shopping-cart tag ticket badge-check
credit-card wallet camera image video music volume-2 mic message-circle send mail at-sign hash pipette
grip-vertical power log-out circle square play pause fast-forward timer gauge fingerprint scan radar type
toggle-left pin bookmark flag funnel arrow-right arrow-left arrow-up arrow-down person-standing hand
circle-user-round shield-check paintbrush text-cursor-input
`.split(/\s+/).filter(Boolean);

const source = await (await fetch(URL)).text();
const all = new Map([...source.matchAll(/\["([^"]+)"\]\s*=\s*"(rbxassetid:\/\/\d+)"/g)].map((match) => [match[1], match[2]]));
const missing = NAMES.filter((name) => !all.has(name));
if (missing.length > 0) {
	console.error(`not in the Lucide pack: ${missing.join(", ")}`);
	process.exit(1);
}

const lines = [...new Set(NAMES)].sort().map((name) => `\t["${name}"] = "${all.get(name)}",`);
writeFileSync(
	OUT,
	[
		"-- Lucide icons (ISC) uploaded to Roblox by Footagesus/Icons (MIT).",
		"-- Generated by tools/build-icons.mjs; do not edit by hand.",
		"",
		"return {",
		...lines,
		"}",
		"",
	].join("\n"),
);
console.log(`wrote ${lines.length} icons to src/Core/IconData.luau`);
