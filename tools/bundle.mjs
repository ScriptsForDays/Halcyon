// Builds src/ into two distributions of the same code:
//
//   dist/Halcyon.luau   one file, for executors to loadstring
//   dist/Halcyon.rbxmx  a Studio model: a Halcyon ModuleScript whose module
//                       definitions are split across child ModuleScripts,
//                       because Studio refuses a script source of 200,000
//                       characters or more
//
// and dist/Halcyon.types.luau, Luau types printed from src/Core/Schema.luau
// by tools/gen-types.luau (needs the luau binary, as the tests do).
//
// Every source module uses relative string requires ("./Signal", "../Core/Theme").
// Each is resolved at build time, so a require that points nowhere fails here
// and never at runtime. Run with --check to fail when dist/ trails src/.

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join, posix, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "src");
const DIST = join(ROOT, "dist");
const SINGLE = join(DIST, "Halcyon.luau");
const MODEL = join(DIST, "Halcyon.rbxmx");
const TYPES = join(DIST, "Halcyon.types.luau");
// Where the Studio parts are also written as plain files, for tools that load
// them into a running Studio session. Not committed.
const STUDIO_PARTS = join(ROOT, ".build", "studio");
const ENTRY = "Halcyon";
const REQUIRE = /require\("(\.\.?\/[^"]+)"\)/g;
// Studio's limit is below 200,000; parts stop well short of it.
const PART_LIMIT = 180000;

function listModules(directory) {
	const found = [];
	for (const name of readdirSync(directory).sort()) {
		const path = join(directory, name);
		if (statSync(path).isDirectory()) {
			found.push(...listModules(path));
		} else if (name.endsWith(".luau")) {
			found.push(path);
		}
	}
	return found;
}

function moduleKey(path) {
	return relative(SRC, path).replace(/\\/g, "/").replace(/\.luau$/, "");
}

const IMPORT = [
	"local modules, loaded, loading = {}, {}, {}",
	"local function import(name)",
	"if loaded[name] ~= nil then",
	"return loaded[name]",
	"end",
	'assert(not loading[name], "Halcyon: circular require of " .. name)',
	"loading[name] = true",
	"local result = modules[name]()",
	"loading[name] = nil",
	"loaded[name] = result",
	"return result",
	"end",
].join("\n");

// One `modules["Key"] = function() ... end` block per source file.
function definitions() {
	const files = listModules(SRC);
	const keys = new Set(files.map(moduleKey));
	const version = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8")).version;
	const blocks = files.map((file) => {
		const key = moduleKey(file);
		const source = readFileSync(file, "utf8").replace(/\r\n/g, "\n").replace(REQUIRE, (_, target) => {
			const resolved = posix.normalize(posix.join(posix.dirname(key), target));
			if (!keys.has(resolved)) {
				throw new Error(`${key}: require("${target}") resolves to ${resolved}, which does not exist`);
			}
			return `import("${resolved}")`;
		});
		// Whole-line comments, blank lines and indentation are left out to
		// keep the output small; src/ keeps them. No source file holds a
		// multi-line string, so no string's contents change.
		const body = source
			.trimEnd()
			.split("\n")
			.filter((line) => line.trim() !== "" && !/^\s*--(?!\[)/.test(line))
			.map((line) => line.trimStart())
			.join("\n")
			.replace("__VERSION__", version);
		return `modules["${key}"] = function()\n${body}\nend`;
	});
	return { blocks, version };
}

function header(version) {
	return [
		`-- Halcyon ${version} | MIT License | https://github.com/ScriptsForDays/Halcyon`,
		"-- Generated by tools/bundle.mjs from src/. Edit the sources, not this file.",
	].join("\n");
}

export function bundle() {
	const { blocks, version } = definitions();
	return [header(version), IMPORT, ...blocks, `return import("${ENTRY}")`, ""].join("\n");
}

// The Studio build: the loader, then the definitions in parts below the limit.
export function studioParts() {
	const { blocks, version } = definitions();
	const parts = [];
	let current = [];
	let length = 0;
	for (const block of blocks) {
		if (block.length > PART_LIMIT) {
			throw new Error(`one module is ${block.length} characters, over the ${PART_LIMIT} a Studio part may hold`);
		}
		if (length + block.length > PART_LIMIT && current.length > 0) {
			parts.push(current);
			current = [];
			length = 0;
		}
		current.push(block);
		length += block.length + 1;
	}
	parts.push(current);

	const main = [
		header(version),
		IMPORT,
		"-- Each child holds some of the module definitions; it is called once with the shared table.",
		"local children = script:GetChildren()",
		"table.sort(children, function(a, b) return a.Name < b.Name end)",
		"for _, child in children do",
		'if child:IsA("ModuleScript") then',
		"require(child)(modules, import)",
		"end",
		"end",
		`return import("${ENTRY}")`,
		"",
	].join("\n");
	const children = parts.map((part, index) => ({
		name: `Part${String(index + 1).padStart(2, "0")}`,
		source: `return function(modules, import)\n${part.join("\n")}\nend\n`,
	}));
	return { main, children };
}

function cdata(text) {
	if (text.includes("]]>")) {
		throw new Error("a module contains ]]>, which cannot sit inside a CDATA section");
	}
	return `<![CDATA[${text}]]>`;
}

function item(name, source, referent, inner = "") {
	return [
		`<Item class="ModuleScript" referent="RBX${referent}">`,
		"<Properties>",
		`<string name="Name">${name}</string>`,
		`<ProtectedString name="Source">${cdata(source)}</ProtectedString>`,
		"</Properties>",
		inner,
		"</Item>",
	].join("\n");
}

export function studioModel() {
	const { main, children } = studioParts();
	const inner = children.map((child, index) => item(child.name, child.source, index + 1)).join("\n");
	return ['<roblox version="4">', item("Halcyon", main, 0, inner), "</roblox>", ""].join("\n");
}

// The types file: the schema module's source, then the generator, run as
// one chunk so the generator sees `Schema`.
export function types() {
	const schema = readFileSync(join(SRC, "Core", "Schema.luau"), "utf8").replace(/\r\n/g, "\n");
	const generator = readFileSync(join(ROOT, "tools", "gen-types.luau"), "utf8").replace(/\r\n/g, "\n");
	const chunk = `local Schema = (function()\n${schema}\nend)()\n\n${generator}`;
	mkdirSync(join(ROOT, ".build"), { recursive: true });
	const path = join(ROOT, ".build", "gen-types.luau");
	writeFileSync(path, chunk);
	const output = execFileSync(process.env.LUAU_BIN || "luau", [path], { encoding: "utf8" });
	return output.replace(/\r\n/g, "\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const single = bundle();
	const model = studioModel();
	const typed = types();
	if (process.argv.includes("--check")) {
		const stale = [
			[SINGLE, single],
			[MODEL, model],
			[TYPES, typed],
		].filter(([path, expected]) => !existsSync(path) || readFileSync(path, "utf8") !== expected);
		if (stale.length > 0) {
			console.error(`${stale.map(([path]) => relative(ROOT, path)).join(", ")} out of date. Run: node tools/bundle.mjs`);
			process.exit(1);
		}
		console.log("dist/ is current");
	} else {
		mkdirSync(DIST, { recursive: true });
		writeFileSync(SINGLE, single);
		writeFileSync(MODEL, model);
		writeFileSync(TYPES, typed);
		const { main, children } = studioParts();
		mkdirSync(STUDIO_PARTS, { recursive: true });
		writeFileSync(join(STUDIO_PARTS, "Halcyon.luau"), main);
		for (const child of children) {
			writeFileSync(join(STUDIO_PARTS, `${child.name}.luau`), child.source);
		}
		writeFileSync(join(STUDIO_PARTS, "parts.txt"), children.map((child) => child.name).join("\n"));
		console.log(`wrote dist/Halcyon.luau (${single.length} characters) and dist/Halcyon.rbxmx (${children.length} parts)`);
	}
}
