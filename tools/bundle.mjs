// Bundles src/ into dist/Halcyon.luau, one file an executor can loadstring.
//
// Every source module uses relative string requires ("./Signal", "../Core/Theme").
// Each is resolved at build time, so a require that points nowhere fails here
// and never at runtime. Run with --check to fail when dist/ trails src/.

import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join, posix, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "src");
const OUT = join(ROOT, "dist", "Halcyon.luau");
const ENTRY = "Halcyon";
const REQUIRE = /require\("(\.\.?\/[^"]+)"\)/g;

function listModules(directory) {
	const found = [];
	for (const name of readdirSync(directory).sort()) {
		const path = join(directory, name);
		if (statSync(path).isDirectory()) {
			found.push(...listModules(path));
		} else if (name.endsWith(".luau")) {
			found.push(path);
		}
	}
	return found;
}

function moduleKey(path) {
	return relative(SRC, path).replace(/\\/g, "/").replace(/\.luau$/, "");
}

export function bundle() {
	const files = listModules(SRC);
	const keys = new Set(files.map(moduleKey));
	const version = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8")).version;
	const parts = [
		`-- Halcyon ${version} | MIT License | https://github.com/ScriptsForDays/Halcyon`,
		"-- Generated by tools/bundle.mjs from src/. Edit the sources, not this file.",
		"",
		"local modules, loaded, loading = {}, {}, {}",
		"",
		"local function import(name)",
		"\tif loaded[name] ~= nil then",
		"\t\treturn loaded[name]",
		"\tend",
		'\tassert(not loading[name], "Halcyon: circular require of " .. name)',
		"\tloading[name] = true",
		"\tlocal result = modules[name]()",
		"\tloading[name] = nil",
		"\tloaded[name] = result",
		"\treturn result",
		"end",
		"",
	];

	for (const file of files) {
		const key = moduleKey(file);
		const source = readFileSync(file, "utf8").replace(/\r\n/g, "\n").replace(REQUIRE, (_, target) => {
			const resolved = posix.normalize(posix.join(posix.dirname(key), target));
			if (!keys.has(resolved)) {
				throw new Error(`${key}: require("${target}") resolves to ${resolved}, which does not exist`);
			}
			return `import("${resolved}")`;
		});
		// Whole-line comments are left out of the bundle to keep it under the
		// 200,000 characters a Studio ModuleScript can hold; src/ keeps them.
		// Blank lines and indentation go too, for the same reason. No source
		// file holds a multi-line string, so no string's contents change.
		const body = source
			.trimEnd()
			.split("\n")
			.filter((line) => line.trim() !== "" && !/^\s*--(?!\[)/.test(line))
			.map((line) => line.trimStart())
			.join("\n");
		parts.push(`modules["${key}"] = function()\n${body}\nend\n`);
	}

	parts.push(`return import("${ENTRY}")\n`);
	const output = parts.join("\n").replace("__VERSION__", version);
	// A Studio ModuleScript holds fewer than 200,000 characters. Past that the
	// bundle still loads through loadstring but can no longer be pasted in.
	if (output.length >= 200000) {
		throw new Error(`the bundle is ${output.length} characters; a Studio ModuleScript holds fewer than 200,000`);
	}
	return output;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const output = bundle();
	if (process.argv.includes("--check")) {
		const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
		if (current !== output) {
			console.error("dist/Halcyon.luau is out of date. Run: node tools/bundle.mjs");
			process.exit(1);
		}
		console.log("dist/Halcyon.luau is current");
	} else {
		mkdirSync(dirname(OUT), { recursive: true });
		writeFileSync(OUT, output);
		console.log(`wrote dist/Halcyon.luau (${output.length} bytes)`);
	}
}
